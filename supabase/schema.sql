-- ROW LEVEL SECURITY
-- ════════════════════════════════════════════════════════════════════
alter table public.administradores enable row level security;
alter table public.destinos        enable row level security;
alter table public.planes          enable row level security;
alter table public.cotizaciones    enable row level security;

-- Administradores: cada admin solo ve su propio registro.
drop policy if exists "admin ve su registro" on public.administradores;
create policy "admin ve su registro" on public.administradores
  for select to authenticated using (user_id = auth.uid());

-- Destinos: lectura pública solo de los activos; gestión solo para admins.
drop policy if exists "destinos publicos" on public.destinos;
create policy "destinos publicos" on public.destinos
  for select to anon, authenticated using (estado = 'activo' or public.es_admin());

drop policy if exists "destinos gestion admin" on public.destinos;
create policy "destinos gestion admin" on public.destinos
  for all to authenticated using (public.es_admin()) with check (public.es_admin());

-- Planes: igual que destinos.
drop policy if exists "planes publicos" on public.planes;
create policy "planes publicos" on public.planes
  for select to anon, authenticated using (estado = 'activo' or public.es_admin());

drop policy if exists "planes gestion admin" on public.planes;
create policy "planes gestion admin" on public.planes
  for all to authenticated using (public.es_admin()) with check (public.es_admin());

-- Cotizaciones: los visitantes SOLO pueden crear solicitudes nuevas.
-- Nadie sin rol de administrador puede leer, modificar ni borrar datos de clientes.
drop policy if exists "crear cotizacion" on public.cotizaciones;
create policy "crear cotizacion" on public.cotizaciones
  for insert to anon, authenticated with check (estado = 'nueva');

drop policy if exists "cotizaciones lectura admin" on public.cotizaciones;
create policy "cotizaciones lectura admin" on public.cotizaciones
  for select to authenticated using (public.es_admin());

drop policy if exists "cotizaciones gestion admin" on public.cotizaciones;
create policy "cotizaciones gestion admin" on public.cotizaciones
  for update to authenticated using (public.es_admin()) with check (public.es_admin());

drop policy if exists "cotizaciones borrado admin" on public.cotizaciones;
create policy "cotizaciones borrado admin" on public.cotizaciones
  for delete to authenticated using (public.es_admin());

-- Permisos explícitos por rol (defensa adicional a RLS).
revoke all on public.cotizaciones from anon;
grant insert on public.cotizaciones to anon;
grant select on public.destinos, public.planes to anon;
