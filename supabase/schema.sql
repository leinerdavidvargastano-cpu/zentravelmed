create extension if not exists pgcrypto;

-- ─── Administradores ────────────────────────────────────────────────
-- Usuarios de Supabase Auth autorizados para gestionar contenido y
-- consultar cotizaciones. Agregar con:
--   insert into public.administradores (user_id) values ('<uuid del usuario>');
create table if not exists public.administradores (
  user_id uuid primary key references auth.users (id) on delete cascade,
  creado_en timestamptz not null default now()
);

create or replace function public.es_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (select 1 from public.administradores where user_id = auth.uid());
$$;

-- ─── Utilidad: fecha de actualización ───────────────────────────────
create or replace function public.set_actualizado_en()
returns trigger language plpgsql as $$
begin
  new.actualizado_en = now();
  return new;
end;
$$;

-- ─── DESTINOS ───────────────────────────────────────────────────────
create table if not exists public.destinos (
  id             bigint generated by default as identity primary key,
  nombre         text not null,
  slug           text not null unique check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  tipo           text not null check (tipo in ('nacional', 'internacional')),
  pais           text not null,
  region         text not null,
  continente     text not null,
  ubicacion      text,
  resumen        text,
  descripcion    text,
  imagen         text,                          -- URL o public_id de Cloudinary
  galeria        text[] not null default '{}',
  categoria      text[] not null default '{}',  -- playa, aventura, cultural, naturaleza...
  actividades    text[] not null default '{}',
  lugares        text[] not null default '{}',
  clima          text,
  creditos       jsonb not null default '[]',   -- créditos de fotografías
  destacado      boolean not null default false,
  estado         text not null default 'activo' check (estado in ('activo', 'inactivo', 'borrador')),
  creado_en      timestamptz not null default now(),
  actualizado_en timestamptz not null default now()
);

create index if not exists destinos_tipo_region_idx on public.destinos (tipo, region);
create index if not exists destinos_destacado_idx on public.destinos (destacado) where estado = 'activo';

drop trigger if exists destinos_actualizado on public.destinos;
create trigger destinos_actualizado before update on public.destinos
  for each row execute function public.set_actualizado_en();

-- ─── PLANES ─────────────────────────────────────────────────────────
create table if not exists public.planes (
  id                  bigint generated by default as identity primary key,
  nombre              text not null,
  slug                text not null unique check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  destino_id          bigint references public.destinos (id) on delete set null,
  descripcion         text,
  duracion_dias       integer check (duracion_dias between 1 and 90),
  duracion_noches     integer check (duracion_noches between 0 and 90),
  precio_referencial  numeric(14, 2) check (precio_referencial is null or precio_referencial > 0),
  moneda              text not null default 'COP' check (moneda in ('COP', 'USD', 'EUR')),
  servicios_incluidos text[] not null default '{}',
  categorias          text[] not null default '{}', -- nacional, internacional, familiar, romantico...
  imagen              text,
  destacado           boolean not null default false,
  estado              text not null default 'activo' check (estado in ('activo', 'inactivo', 'borrador')),
  creado_en           timestamptz not null default now(),
  actualizado_en      timestamptz not null default now()
);

create index if not exists planes_destino_idx on public.planes (destino_id);

drop trigger if exists planes_actualizado on public.planes;
create trigger planes_actualizado before update on public.planes
  for each row execute function public.set_actualizado_en();

-- ─── COTIZACIONES ───────────────────────────────────────────────────
create table if not exists public.cotizaciones (
  id              uuid primary key default gen_random_uuid(),
  nombre          text not null check (char_length(nombre) between 3 and 120),
  telefono        text not null check (telefono ~ '^\+?[0-9 ]{7,20}$'),
  correo          text check (correo is null or correo ~* '^[^@\s]+@[^@\s]+\.[^@\s]+$'),
  destino         text not null check (char_length(destino) between 2 and 120),
  fecha_viaje     date,
  adultos         integer not null default 1 check (adultos between 1 and 50),
  ninos           integer not null default 0 check (ninos between 0 and 50),
  presupuesto     text check (char_length(presupuesto) <= 60),
  comentarios     text check (char_length(comentarios) <= 1000),
  origen          text check (char_length(origen) <= 120), -- plan o página desde donde se envió
  fecha_solicitud timestamptz not null default now(),
  estado          text not null default 'nueva'
                  check (estado in ('nueva', 'en_proceso', 'cotizada', 'cerrada', 'descartada'))
);

create index if not exists cotizaciones_fecha_idx on public.cotizaciones (fecha_solicitud desc);
create index if not exists cotizaciones_estado_idx on public.cotizaciones (estado);

